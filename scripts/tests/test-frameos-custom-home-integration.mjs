import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html = fs.readFileSync(new URL('../../examples/frameos/frameos-touchscreen-panel.html', import.meta.url), 'utf8');
assert.match(html, /id="custom-home"/, 'Custom Home has its own visible DOM, not a themed HA card');
assert.match(html, /script-src 'self' 'unsafe-inline'/, 'custom code remains same-origin');
assert.match(html, /frameos-custom-home\.js\?v=/);
assert.match(html, /frameos-custom-home\.css\?v=/);
const script = html.match(/<script>\s*([\s\S]*?)\s*<\/script>/)[1];
const listeners = new Map(), childListeners = new Map(), timers = [];
const classes = new Set();
let mounts = 0, destroyed = 0, options;
const hass = { states: {}, callService() { throw new Error('integration must never send commands'); }, connection: { connected: true } };
const app = { hass: null };
let root = { querySelector: s => s === 'home-assistant' ? app : null, querySelectorAll: () => [], nodeType: 9 };
const panel = { src: '', contentDocument: root, contentWindow: { location: { pathname: '/frameos-touchscreen/home' }, focus() {}, addEventListener(n,f) {childListeners.set(n,f);}, removeEventListener(n) {childListeners.delete(n);} }, classList: { toggle(n,on) {on ? classes.add(n) : classes.delete(n);}}, addEventListener(n,f) {listeners.set('panel:'+n,f);}, focus() {} };
const custom = { hidden: true, textContent: '', focus() {} };
const home = { hidden: true };
const loading = { hidden: false, textContent:'', classList: {add(){},remove(){}} };
const status = {textContent:''};
const c = { document: {getElementById: id => ({panel,'custom-home':custom,'home-chrome':home,loading,status})[id]}, location: {hash:'#home',pathname:'/local/frameos-touchscreen-panel.html',search:''}, history:{ replaceState(_a,_b,url){c.location.hash=url.slice(url.indexOf('#'));}}, MutationObserver:class{observe(){} disconnect(){}}, setTimeout(fn,delay){timers.push({fn,delay,active:true});return timers.length;}, clearTimeout(id){if(timers[id-1])timers[id-1].active=false;}, FrameOSCustomHome:{mount(_root,opts){assert.equal(_root,custom);mounts++;options=opts;return{destroy(){destroyed++;},refresh(){}};}}, addEventListener(n,f){listeners.set(n,f);} };
c.window=c;
vm.runInNewContext(script,c);
listeners.get('panel:load')();
assert.equal(mounts,0,'not mounted before authenticated state exists');
app.hass=hass;
// Only bounded discovery timers execute, not the legacy readiness timeout.
for(let n=0;n<5 && !mounts;n++){const t=timers.find(t=>t.active&&t.delay===50);assert.ok(t);t.active=false;t.fn();}
assert.equal(mounts,1);
assert.equal(custom.hidden,false);
assert.equal(home.hidden,true,'no duplicate old Home header');
assert.ok(classes.has('custom-home-backend'),'HA iframe becomes an invisible session owner');
assert.equal(loading.hidden,true);
const facade = options.getHass();
assert.notEqual(facade,hass,'custom renderer receives a narrow facade, not the authenticated HA object');
assert.equal(facade.connection,undefined,'HA connection is not passed through');
assert.equal(facade.connected,true);
assert.deepEqual(Object.keys(facade.states),[]);
assert.ok(Object.isFrozen(facade));
hass.states['weather.forecast_home']={state:'rainy',attributes:{temperature:62,temperature_unit:'°F',private_marker:'hidden'}};
hass.states['weather.parents_weather']={state:'sunny',attributes:{temperature:99}};
const weatherFacade=options.getHass();
assert.equal(weatherFacade.states['weather.forecast_home']?.attributes.temperature,62,'wrapper exposes household forecast state');
assert.equal(weatherFacade.states['weather.forecast_home']?.attributes.private_marker,undefined);
assert.equal(weatherFacade.states['weather.parents_weather'],undefined,'unrelated home weather stays outside facade');

await assert.rejects(facade.callService('light','turn_on',{entity_id:'light.any'}),/Unsupported/);
await assert.rejects(facade.callService('climate','set_hvac_mode',{entity_id:'climate.other',hvac_mode:'heat'}),/Unsupported/);
options.navigate('cameras');
assert.equal(panel.src,'/frameos-touchscreen/cameras?kiosk');
assert.equal(destroyed,1);
assert.equal(custom.hidden,true);
assert.ok(!classes.has('custom-home-backend'));
c.location.hash='#home';panel.contentWindow.location.pathname='/frameos-touchscreen/home';listeners.get('hashchange')();listeners.get('panel:load')();
assert.equal(mounts,2);
panel.contentWindow.location.pathname='/auth/authorize';childListeners.get('location-changed')();
assert.equal(destroyed,2,'auth SPA transition destroys custom view');
assert.equal(custom.hidden,true);
assert.ok(!classes.has('custom-home-backend'),'sign-in must be visible');
assert.equal(status.textContent,'Sign-in required');
panel.contentWindow.location.pathname='/frameos-touchscreen/home';childListeners.get('location-changed')();
assert.equal(mounts,3,'return from authentication remounts');
const oldOptions=options;
root={querySelector:()=>null,querySelectorAll:()=>[],nodeType:9};panel.contentDocument=root;
listeners.get('panel:load')();
assert.equal(destroyed,3,'new iframe document invalidates old bridge');
assert.equal(oldOptions.getHass(),null,'no stale hass allowed after reload');
listeners.get('pagehide')();
assert.ok(!timers.some(t=>t.active&&t.delay===50),'pagehide cancels bridge and readiness probes');
// A renderer failure must not hide the authenticated native fallback.
root={querySelector:()=>app,querySelectorAll:()=>[],nodeType:9};panel.contentDocument=root;
c.FrameOSCustomHome.mount=()=>{throw new Error('broken renderer');};
assert.doesNotThrow(()=>listeners.get('panel:load')());
assert.equal(custom.hidden,true);
assert.ok(!classes.has('custom-home-backend'));
assert.equal(home.hidden,false,'native Home header/fallback restored');
listeners.get('pagehide')();
console.log('Custom Home integration: session discovery, navigation, auth and document lifecycle passed');
assert.doesNotMatch(html,/wyattf1995|gmail_com/,'public wrapper discovers bounded calendar metadata without private account identifiers');
